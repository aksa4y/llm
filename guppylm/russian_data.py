for location in LOCATIONS:
    questions, answers = [], []
    # Each pair is a complete scene, not a random cross-product of facts.
    for event, observation in EVENTS:
        for lead in ["Представь", "Расскажи", "Опиши", "Как ты себя чувствуешь"]:
            questions.append(f"{lead}: ты {location}, {event}.")
            answers.append(f"Я {location}. {observation} Тихонько двигаю плавниками.")
    # Separate families preserve scene pairings in build().
    FAMILIES.append((questions, answers))


def render(question, answer):
    return '\n'.join(f'<|im_start|>{role}\n{text}<|im_end|>' for role, text in [('system', SYSTEM), ('user', question), ('assistant', answer)])


def build(output='data', seed=42):
    rng = random.Random(seed)
    families = list(enumerate(FAMILIES))
    rng.shuffle(families)
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    counts = {}
    for split, selected in [('eval', families[:4]), ('train', families[4:])]:
        rows = []
        for family, (questions, answers) in selected:
            for question, answer in (zip(questions, answers) if family >= 20 else ((q, a) for q in questions for a in answers)):
                rows.append({'text': render(question, answer), 'family': family, 'source': 'original-synthetic-ru-v1'})
        rng.shuffle(rows)
        path = output / f'{split}.jsonl'
        path.write_text(''.join(json.dumps(row, ensure_ascii=False) + '\n' for row in rows), encoding='utf-8')
        counts[split] = {'rows': len(rows), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}
    (output / 'manifest.json').write_text(json.dumps({'seed': seed, 'license': 'CC0-1.0', 'language': 'ru', 'split': 'disjoint template families', 'files': counts}, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    return counts


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--data-dir', default='data')
    args = parser.parse_args()
    print(build(args.data_dir))


if __name__ == '__main__':
    main()
